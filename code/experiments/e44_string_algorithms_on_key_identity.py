"""E44: what the AutoPKG key-identity benchmark actually ranks.

WHY. E20 reports a comprehensive loss: AutoPKG's 14B decision agent reaches F1 0.6355 on deciding
whether two raw spec keys name the same attribute, and ESCROW reaches 0.0008. Before that comparison
is read as evidence about language, the benchmark deserves a floor. Its gold is built in
`e20_headtohead.py` by

    fam[norm_key(k)].add(k)                       a pair is positive when the strings agree
    norm_key(k) = NORM_RE.sub("", k.lower())      after lowercasing and stripping punctuation

so the ground truth is the output of a string function, and the right question is not whether a
language model beats a graph rule on it, but what any string method scores.

THE METHODS, none of which reads a language model, all on the identical gold `build_gold` produces
from the identical records `load_records` produces:

  norm_key            the gold's own definition, applied as a predictor. The ceiling by construction.
  casefold            lowercase and compare. Six lines older than the field.
  alnum               lowercase and drop everything not alphanumeric.
  strip_spaces        lowercase and drop whitespace only.
  edit ratio          difflib similarity, threshold swept, oracle best on the test labels
  token jaccard       word sets, threshold swept, oracle best on the test labels
  char 3-gram cosine  term frequency over character trigrams, threshold swept, oracle best
  prefix              equal for the first n characters, n swept, oracle best

The swept methods are given their best threshold on the test labels and it is stated as such, which
is the fairness rule this paper applies to every baseline: an upper bound they could not have in use.

WHAT THIS DOES NOT SHOW. None of these is a contribution and none is proposed as one. If plain
lowercasing beats the language model, that says what the benchmark measures. It says nothing about
whether two differently named keys carry the same role, which is the decision the paper says is open
and which this gold does not record.
"""
from __future__ import annotations
import collections, difflib, itertools, json, math, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.environ.get("ESCROW_ROOT") or os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "code"))
sys.path.insert(0, os.path.join(ROOT, "code", "experiments"))

from lazada_c2_rawkey import load_records, norm_key

# build_gold is copied verbatim from e20_headtohead.py rather than imported, because importing that
# module executes AutoPKG's prompt file at load time. The copy is generated by reading the source,
# so it cannot drift silently: code/tests/test_e44_gold_matches_e20.py asserts the two are identical.

def build_gold(recs):
    keyfreq = collections.Counter()
    for r in recs:
        keyfreq.update(r.keys())
    fam = collections.defaultdict(set)
    for k in keyfreq:
        fam[norm_key(k)].add(k)
    pos = set()
    for n, v in fam.items():
        if not n or len(v) < 2:
            continue
        vs = sorted(v)
        for a, b in itertools.combinations(vs, 2):
            pos.add((a, b))
    neg = set()
    for r in recs:
        ks = sorted(r.keys())
        for a, b in itertools.combinations(ks, 2):
            neg.add((a, b))
    collide = pos & neg
    neg -= collide                    # a pair attested as co-present is not a pure variant
    pos -= collide
    return keyfreq, pos, neg, len(collide)

OUT = os.path.join(ROOT, "results", "e44_string_algorithms_on_key_identity.json")

# the two numbers this is a floor for, from results/e20_full_withllm.json
REFERENCE = {"autopkg_kgd_llm_f1": 0.6355, "escrow_f1": 0.0008}


def f1(pos, neg, pred):
    tp = sum(1 for a, b in pos if pred(a, b))
    fp = sum(1 for a, b in neg if pred(a, b))
    fn = len(pos) - tp
    p = tp / (tp + fp) if tp + fp else 0.0
    r = tp / (tp + fn) if tp + fn else 0.0
    f = 2 * p * r / (p + r) if p + r else 0.0
    return dict(tp=tp, fp=fp, fn=fn, precision=round(p, 4), recall=round(r, 4), f1=round(f, 4))


def trigrams(s):
    s = " " + s.lower() + " "
    return collections.Counter(s[i:i + 3] for i in range(max(len(s) - 2, 1)))


def cosine(ca, cb):
    dot = sum(v * cb[k] for k, v in ca.items() if k in cb)
    na = math.sqrt(sum(v * v for v in ca.values()))
    nb = math.sqrt(sum(v * v for v in cb.values()))
    return dot / (na * nb) if na and nb else 0.0


def main():
    recs, pids, stats = load_records()
    keyfreq, pos, neg, collided = build_gold(recs)
    pos, neg = sorted(pos), sorted(neg)
    print(f"gold: {len(pos)} positive, {len(neg)} negative, {collided} collisions dropped")

    report = {"experiment": "E44 what the AutoPKG key-identity benchmark ranks",
              "gold": {"definition": "a pair is positive when norm_key(a) == norm_key(b), "
                                     "norm_key = lowercase then strip non-alphanumeric",
                       "positive_pairs": len(pos), "negative_pairs": len(neg),
                       "collisions_dropped": collided},
              "reference_numbers_this_is_a_floor_for": REFERENCE,
              "fixed_rules": {}, "swept_rules": {}}

    fixed = {
        "norm_key_the_golds_own_definition": lambda a, b: norm_key(a) == norm_key(b),
        "casefold_only": lambda a, b: a.lower() == b.lower(),
        "lowercase_strip_non_alphanumeric": lambda a, b: (re.sub(r"[^a-z0-9]", "", a.lower())
                                                          == re.sub(r"[^a-z0-9]", "", b.lower())),
        "lowercase_strip_whitespace": lambda a, b: (re.sub(r"\s+", "", a.lower())
                                                    == re.sub(r"\s+", "", b.lower())),
    }
    for name, fn in fixed.items():
        r = f1(pos, neg, fn)
        report["fixed_rules"][name] = r
        print(f"  {name:36s} P={r['precision']:.4f} R={r['recall']:.4f} F1={r['f1']:.4f}")

    cache3 = {}

    def tri(s):
        if s not in cache3:
            cache3[s] = trigrams(s)
        return cache3[s]

    swept = {
        "edit_ratio": (lambda t: (lambda a, b: difflib.SequenceMatcher(None, a.lower(),
                                                                      b.lower()).ratio() >= t),
                       [0.5, 0.6, 0.7, 0.8, 0.85, 0.9, 0.95, 1.0]),
        "token_jaccard": (lambda t: (lambda a, b: _jac(a, b) >= t),
                          [0.3, 0.5, 0.6, 0.7, 0.8, 0.9, 1.0]),
        "char_trigram_cosine": (lambda t: (lambda a, b: cosine(tri(a), tri(b)) >= t),
                                [0.5, 0.6, 0.7, 0.8, 0.9, 0.95, 1.0]),
        "shared_prefix": (lambda n: (lambda a, b: a.lower()[:int(n)] == b.lower()[:int(n)]
                                     and min(len(a), len(b)) >= int(n)),
                          [3, 4, 5, 6, 8, 10]),
    }
    for name, (mk, grid) in swept.items():
        rows = []
        for t in grid:
            r = f1(pos, neg, mk(t))
            r["knob"] = t
            rows.append(r)
            print(f"  {name:26s} knob {t:<5} P={r['precision']:.4f} R={r['recall']:.4f} "
                  f"F1={r['f1']:.4f}", flush=True)
        best = max(rows, key=lambda r: r["f1"])
        report["swept_rules"][name] = {"oracle_best_on_test_labels": best, "sweep": rows}
        print(f"  -> {name}: oracle best F1 {best['f1']:.4f} at knob {best['knob']}")

    all_f1 = ([(k, v["f1"]) for k, v in report["fixed_rules"].items()]
              + [(k, v["oracle_best_on_test_labels"]["f1"]) for k, v in report["swept_rules"].items()])
    best_name, best_f1 = max(all_f1, key=lambda kv: kv[1])
    cheap = report["fixed_rules"]["casefold_only"]["f1"]
    report["headline"] = {
        "best_string_method": {"name": best_name, "f1": best_f1},
        "plain_lowercase_f1": cheap,
        "autopkg_kgd_llm_f1": REFERENCE["autopkg_kgd_llm_f1"],
        "escrow_f1": REFERENCE["escrow_f1"],
        "beats_the_language_model": sorted(k for k, v in all_f1
                                           if v > REFERENCE["autopkg_kgd_llm_f1"]),
        "reading": ("the gold is a string function, so this benchmark ranks normalisers; it does "
                    "not record whether two different names carry one role, which is the decision "
                    "the paper says is open"),
    }
    print("\n" + json.dumps(report["headline"], indent=2))
    json.dump(report, open(OUT, "w"), indent=2)
    print("written", OUT)


def _jac(a, b):
    sa = set(re.findall(r"[a-z0-9]+", a.lower()))
    sb = set(re.findall(r"[a-z0-9]+", b.lower()))
    u = sa | sb
    return len(sa & sb) / len(u) if u else 0.0


if __name__ == "__main__":
    main()
