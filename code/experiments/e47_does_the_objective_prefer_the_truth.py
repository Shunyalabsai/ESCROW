"""E47: does L_batch have the planted truth as its optimum, or does it prefer something else?

WHY. The scope proposition explains MusicBrainz 20K and ReVerb45K: both ask for groups of about two,
which the membership column prices out of a stream of that length. It does NOT explain the cases
where our own conditions are met and we still lose: the E33/E34 cover fixture, the Wikidata cover
benchmark, and the encyclopedia stream. Something else is wrong there, and there are only two
candidates. Either the objective ranks the right answer first and the search does not find it, which
is an engineering problem, or the objective does not rank the right answer first, which is a
modelling problem and a much more serious one.

E46 removed three explanations. Accrual is not starved, the largest live candidates reach the
cohorts their seed pairs allow. The price is not the obstacle, both scope clauses hold with room.
The repair pass is not destroying good nodes, since removing it returns a K near the truth at a worse
omega. What was never tested is the question underneath all three.

THE TEST. Build the planted allocation as an actual graph state and ask the shipped objective to
score it, against the state the engine reaches on the same stream and against the empty graph. A
cell carries the group that generated its value, so the oracle assignment is exact and is the most
favourable reading of the truth available. Then:

  L_batch(truth) < L_batch(found)   the objective is right, the search is at fault, and the fix is
                                    a better search
  L_batch(truth) > L_batch(found)   the objective prefers a wrong answer, and no search can rescue
                                    it. That would be the most important negative result in this
                                    project and it would have to be reported as one.

Nothing here is tuned. The oracle state is constructed once, scored once, and printed with the gap.
"""
from __future__ import annotations
import json
import math
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.environ.get("ESCROW_ROOT") or os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "code"))
sys.path.insert(0, os.path.join(ROOT, "code", "experiments"))

from escrow.engine import EscrowGraph, Node, ValueBlock
from escrow.batch import BatchObjective
from escrow.provenance import stamped

OUT = os.path.join(ROOT, "results", "e47_does_the_objective_prefer_the_truth.json")


def cover_fixture(n=1500, groups=8, shared=12, private=0, kpg=3, vals=8, noise=0.1, seed=0):
    """E33/E34's fixture. The value carries the group that generated it, so the oracle
    cell assignment below is exact rather than inferred."""
    rng = random.Random(seed)
    pool = [f"s{i}" for i in range(shared)]
    gkeys = {gi: rng.sample(pool, kpg) + [f"p{gi}_{j}" for j in range(private)]
             for gi in range(groups)}
    recs, truth, gen = [], [], []
    for _ in range(n):
        size = rng.choices([1, 2, 3], weights=[0.5, 0.3, 0.2])[0]
        gs = rng.sample(range(groups), size)
        rec, who = {}, {}
        for gi in gs:
            for k in gkeys[gi]:
                og = rng.randrange(groups) if rng.random() < noise else gi
                rec[k] = f"g{og}v{rng.randrange(vals)}"
                who[k] = og                      # the group that generated this cell
        recs.append(rec)
        truth.append(frozenset(gs))
        gen.append(who)
    return recs, truth, gen, gkeys


def background_only(recs):
    """Process the stream with minting suppressed, so every cell stays background owned and the
    key inventories, background counts and per-record ledgers are exactly as the engine builds
    them. This is the K = 0 state."""
    g = EscrowGraph()
    b = BatchObjective(g).install()
    g._mint = lambda *a, **k: None               # suppress minting only
    for r in recs:
        g.process(r)
    return g, b


def install_oracle(g, truth, gen):
    """Move every cell to the node of the group that generated its value, when that group is one
    the record actually belongs to. Noise cells, whose generating group is not in the record, stay
    in the background: the truth cannot claim them."""
    members = {}
    for rid, gs in enumerate(truth, start=1):
        for gi in gs:
            members.setdefault(gi, set()).add(rid)
    for gi in sorted(members):
        g.next_id += 1
        w = Node(nid=g.next_id, t=len(members[gi]), birth_n=0)
        w.members = set(members[gi])
        for rid in w.members:
            who = gen[rid - 1]
            for kname, owner_g in who.items():
                if owner_g != gi:
                    continue                     # this cell was generated by another group
                ki = g.keys.get(kname)
                if ki is None:
                    continue
                kid = ki.kid
                vid = g.record_vals.get(rid, {}).get(kid)
                if vid is None:
                    continue
                if g.record_owner.get(rid, {}).get(kid, 0) != 0:
                    continue                     # already claimed by an earlier group
                w.S.add(kid)
                w.pub.setdefault(kid, set()).add(rid)
                blk = w.blocks.get(kid)
                if blk is None:
                    blk = w.blocks[kid] = ValueBlock()
                blk.observe(vid)
                ki.background.unobserve(vid)
                g.record_owner.setdefault(rid, {})[kid] = w.nid
        # Presence is a property of MEMBERSHIP, not of who owns the value cell: the engine sets
        # pub[kid] to every member publishing kid (engine._mint), independent of ownership. Setting
        # it from the claimed cells instead understates the presence block and made every oracle
        # state look cheaper than it is. Corrected 2026-09-08.
        for kid in w.S:
            w.pub[kid] = {r for r in w.members if kid in g.record_keys.get(r, ())}
        for kid in w.S:
            w.p[kid] = len(w.pub.get(kid, ()))
            g.ix2.setdefault(kid, set()).add(w.nid)
            for vid in w.blocks[kid].counts:
                g.ix1.setdefault((kid, vid), set()).add(w.nid)
        g.nodes[w.nid] = w
        g.K += 1
    return g


def engine_state(recs, cadence=100):
    g = EscrowGraph()
    b = BatchObjective(g).install()
    for i, r in enumerate(recs, 1):
        g.process(r)
        if i % cadence == 0:
            b.repair()
    b.repair(full=True)
    return g, b


def main():
    rows = []
    print(f"{'seed':>4} {'pool':>5} | {'empty':>10} {'engine':>10} {'K':>3} | "
          f"{'truth':>10} {'K':>3} | {'truth - engine':>14}")
    for shared in (12, 24):
        for seed in (0, 1, 2):
            recs, truth, gen, _ = cover_fixture(shared=shared, seed=seed)

            g0, b0 = background_only(recs)
            l_empty = b0.total()

            g1, b1 = background_only(recs)
            install_oracle(g1, truth, gen)
            l_truth, k_truth = b1.total(), g1.K

            g2, b2 = engine_state(recs)
            l_found, k_found = b2.total(), g2.K

            gap = l_truth - l_found
            rows.append({"shared_key_pool": shared, "seed": seed,
                         "L_empty": round(l_empty, 1),
                         "L_engine": round(l_found, 1), "K_engine": int(k_found),
                         "L_truth": round(l_truth, 1), "K_truth": int(k_truth),
                         "truth_minus_engine_bits": round(gap, 1),
                         "objective_prefers_the_truth": bool(gap < 0)})
            print(f"{seed:>4} {shared:>5} | {l_empty:>10.1f} {l_found:>10.1f} {k_found:>3} | "
                  f"{l_truth:>10.1f} {k_truth:>3} | {gap:>+14.1f}", flush=True)

    prefers = sum(1 for r in rows if r["objective_prefers_the_truth"])
    report = {
        "experiment": "E47 does L_batch have the planted truth as its optimum",
        "fixture": "the E33/E34 cover fixture, 1500 records, 8 groups, all keys from a shared pool",
        "oracle": ("every cell is given to the group that generated its value, where that group is "
                   "one the record belongs to; noise cells stay in the background"),
        "rows": rows,
        "headline": {
            "cells_where_the_objective_prefers_the_truth": prefers,
            "of": len(rows),
            "mean_truth_minus_engine_bits": round(
                sum(r["truth_minus_engine_bits"] for r in rows) / len(rows), 1),
            "reading": ("negative bits mean the truth is the shorter description and the search is "
                        "at fault; positive bits mean the objective ranks the engine's wrong answer "
                        "above the planted truth, which no search can repair"),
        },
    }
    print("\n" + json.dumps(report["headline"], indent=2))
    json.dump(stamped(report), open(OUT, "w"), indent=2)
    print("written", OUT)


if __name__ == "__main__":
    main()
